export const DRAW_WORD_COUNT = DRAW_WORDS.length;

function randInt(n) {
  if (globalThis.crypto?.getRandomValues) {
    const b = new Uint32Array(1);
    globalThis.crypto.getRandomValues(b);
    return b[0] % n;
  }
  return Math.floor(Math.random() * n);
}

// 隨機抽一題（可傳入 usedWords 集合以避免同一局重複）
export function drawOneWord(used) {
  if (!used || used.length >= DRAW_WORDS.length) {
    return DRAW_WORDS[randInt(DRAW_WORDS.length)];
  }
  const usedSet = new Set(used);
  for (let tries = 0; tries < 40; tries++) {
    const cand = DRAW_WORDS[randInt(DRAW_WORDS.length)];
    if (!usedSet.has(cand.w)) return cand;
  }
  return DRAW_WORDS.find((x) => !usedSet.has(x.w)) || DRAW_WORDS[randInt(DRAW_WORDS.length)];
}
