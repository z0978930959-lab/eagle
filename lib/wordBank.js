export const WORD_BANK = [
  ...ANIMALS, ...FOOD, ...OBJECTS, ...PLACES, ...WORLD,
  ...NATURE, ...PEOPLE, ...ACTIONS, ...ABSTRACT,
];

function shuffle(a) {
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * 抽 n 個詞排盤面。
 * 核心規則：挑出來的詞「兩兩不共用任何一個中文字」——
 * 這樣就不會出現「影／影子」、「火／火山」、「星／土星」這種
 * 令人混淆的組合，也讓「提示不得提到盤面上的字」判定得乾淨。
 */
export function drawWords(n = 25) {
  const pool = shuffle(WORD_BANK.slice());
  const picked = [];
  const usedChars = new Set();

  for (const w of pool) {
    if (picked.length >= n) break;
    const chars = [...w];
    if (chars.some((c) => usedChars.has(c))) continue;
    picked.push(w);
    chars.forEach((c) => usedChars.add(c));
  }

  // 保險：詞庫足夠時走不到這裡。萬一湊不滿，退一步只要求「不互為子字串」。
  if (picked.length < n) {
    for (const w of pool) {
      if (picked.length >= n) break;
      if (picked.includes(w)) continue;
      if (picked.some((p) => p.includes(w) || w.includes(p))) continue;
      picked.push(w);
    }
  }

  return shuffle(picked);
}
